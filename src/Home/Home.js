const StatCounter = ({ stat }) => {
  const { ref, inView } = useInView({
    triggerOnce: true, // Only trigger the count-up once
    threshold: 0.1, // Trigger when 10% of the element is in view
  });

  const suffix =
    stat.label === "Total Valuation" || stat.label === "Revenue Generated By Startups"
      ? " Cr+"
      : stat.label === "Sectors In Focus" || stat.label === "Women Entrepreneurs"
        ? "+"
        : "";

  return (
    <div className="stat-cell font-dmsans">
      <div className="stat-cell__value" ref={ref}>
          {inView ? (
            <CountUp
              end={stat.value}
              suffix={suffix}
              duration={2}
            />
          ) : (
            <span>
              {stat.value}
              {suffix}
            </span>
          )}
      </div>

      <div className="stat-cell__label">{stat.label}</div>

      {stat.label === "Active Teams" && (
        <div className="stat-cell__note">(till April-2026 Cohort)</div>
      )}
      {stat.label === "Total Number of Teams Trained" && (
        <div className="stat-cell__note">(till April-2026 Cohort)</div>
      )}
    </div>
  );
};

